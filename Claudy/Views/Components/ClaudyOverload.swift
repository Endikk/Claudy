    /// Length of the one-off part, before the dead loop starts.
    static let introDuration: TimeInterval =
        TimeInterval(durations.dropLast(deadLoopCount).reduce(0, +)) / 1000

    /// The frame to show `elapsed` seconds after the quota filled up. A `nil` elapsed means the
    /// explosion was not witnessed (the app opened already full): straight to the dead loop.
    static func frameIndex(elapsed: TimeInterval?) -> Int {
        let deadStart = frames.count - deadLoopCount
        guard var remaining = elapsed.map({ max($0, 0) }) else {
            return deadStart
        }
        for index in 0..<deadStart {
            let duration = TimeInterval(durations[index]) / 1000
            if remaining < duration { return index }
            remaining -= duration
        }
        let loopMs = durations.suffix(deadLoopCount).reduce(0, +)
        var inLoop = Int(remaining * 1000) % max(loopMs, 1)
        for index in deadStart..<frames.count {
            if inLoop < durations[index] { return index }
            inLoop -= durations[index]
        }
        return frames.count - 1
    }
